export function resolveLocale(preference: LanguagePreference, deviceLocale: string): AppLocale {
  if (preference !== 'system') return preference;
  return deviceLocale.toLowerCase().startsWith('zh') ? 'zh-Hant' : 'en';
}

export function translate(
  locale: AppLocale,
  source: string,
  values?: Record<string, string | number>,
): string {
  const message = locale === 'zh-Hant' ? TRADITIONAL_CHINESE[source] ?? source : source;
  if (!values) return message;
  return message.replace(/\{(\w+)\}/g, (placeholder, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : placeholder,
  );
}

export function deviceLocale(): string {
  try {
    return Intl.DateTimeFormat().resolvedOptions().locale || 'en';
  } catch {
    return 'en';
  }
}
